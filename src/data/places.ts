export const placeById = new Map(places.map((p) => [p.id, p]));
export const placeBySlug = new Map(places.map((p) => [p.slug, p]));

export function getPlace(id: string | undefined) {
  return id ? placeById.get(id) : undefined;
}
export function getPlaceBySlug(slug: string | undefined) {
  return slug ? placeBySlug.get(slug) : undefined;
}
export function placesForDistrict(districtId: string): Place[] {
  return places.filter((p) => p.districtId === districtId && p.published);
}
export function hiddenPlacesForDistrict(districtId: string): Place[] {
  return places.filter((p) => p.districtId === districtId && p.published && p.hidden);
}

/** Districts that currently have at least one published place. */
export function districtHasPlaces(districtId: string): boolean {
  return places.some((p) => p.districtId === districtId && p.published);
}
